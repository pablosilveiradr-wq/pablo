export type LibEntry = {
  /** Stable slug, also the registry key and the export file name. */
  readonly id: string;
  /** What the editor searches for. */
  readonly name: string;
  readonly cat: string;
  /** Undefined while the icon is still to be drawn. */
  readonly C?: React.FC<IconProps>;
};

const e = (
  id: string,
  name: string,
  C?: React.FC<IconProps>,
): Omit<LibEntry, "cat"> => ({ id, name, C });

const cat = (name: string, entries: Omit<LibEntry, "cat">[]): LibEntry[] =>
  entries.map((x) => ({ ...x, cat: name }));

